/**
 * Get archetype by key, fallback to ECOMMERCE
 */
export function getBusinessArchetype(businessType?: string | null): BusinessArchetype {
  if (!businessType) return BUSINESS_ARCHETYPES.ECOMMERCE;
  const upper = businessType.toUpperCase().trim();
  return BUSINESS_ARCHETYPES[upper] || BUSINESS_ARCHETYPES.ECOMMERCE;
}
